package com.musicremover.app.processing.internal

import android.net.Uri
import android.util.Log
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.musicremover.app.processing.internal.YtDlpTestSupport.TAG
import java.io.File
import java.util.UUID
import kotlinx.coroutines.runBlocking
import org.junit.After
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith

/**
 * The imported cookies.txt reaches yt-dlp as `--cookies <per-job copy>`, the copy is deleted afterwards and
 * the stored file is never touched. yt-dlp rewrites the file it was given on exit (with its own header), so
 * that header in the copy proves the option was passed. Uses a dummy cookie for a test domain; the
 * yt-dlp run needs internet (default "Me at the zoo", or `muremTestUrl`).
 */
@RunWith(AndroidJUnit4::class)
class YtDlpCookiesTest {
    private val ctx = InstrumentationRegistry.getInstrumentation().targetContext
    private val store = CookieStore(ctx)
    private lateinit var work: File
    private val dummy = (
        "# Netscape HTTP Cookie File\n" +
            ".murem-test.invalid\tTRUE\t/\tFALSE\t2000000000\tmurem_test\tDUMMY_VALUE_123456\n"
        ).toByteArray()

    @Before
    fun setUp() {
        work = File(ctx.filesDir, "work/cookies-test-${UUID.randomUUID()}").apply { mkdirs() }
        val src = File(ctx.cacheDir, "dummy-cookies.txt").apply { writeBytes(dummy) }
        val r = store.import(Uri.fromFile(src))
        src.delete()
        assertEquals(CookieStore.ImportResult.Imported(CookiesTxt.Summary(1, listOf("murem-test.invalid"))), r)
    }

    @After
    fun tearDown() {
        store.deleteAll()
        if (::work.isInitialized) work.deleteRecursively()
    }

    private val stored get() = File(ctx.filesDir, "cookies/sites/murem-test.invalid.txt")

    @Test
    fun importRejectsInvalidFileAndKeepsTheOldOne() {
        val bad = File(ctx.cacheDir, "bad-cookies.txt").apply { writeText("[{\"domain\": \".instagram.com\"}]") }
        val r = store.import(Uri.fromFile(bad))
        bad.delete()
        assertEquals(CookieStore.ImportResult.Rejected(CookiesTxt.Invalid.MALFORMED_LINE, 1), r)
        assertArrayEquals(CookiesTxt.mergeLines(null, dummy.decodeToString()).toByteArray(), stored.readBytes())
        assertEquals(1, store.summary()?.count)
    }

    @Test
    fun ytDlpGetsADeletedCopyAndTheStoredFileIsUnchanged() = runBlocking<Unit> {
        assumeTrue("no internet", YtDlpTestSupport.internetAvailable())
        YtDlpTestSupport.maybeUpdate(ctx)
        val dir = File(work, "cookies")
        var copy: File? = null
        val info = withJobCookies(store, dir) { cookies ->
            assertNotNull(cookies)
            copy = cookies!!.file
            assertEquals(dir.canonicalPath, copy!!.parentFile!!.canonicalPath)
            assertNotEquals(stored.canonicalPath, copy!!.canonicalPath)
            assertTrue("DUMMY_VALUE_123456" in cookies.secrets)
            val i = YtDlpDownloader(ctx).info(YtDlpTestSupport.url, "test-cookies-${UUID.randomUUID()}", cookies)
            // yt-dlp saved its cookie jar into the copy: --cookies pointed at it
            val written = copy!!.readText()
            assertTrue("yt-dlp did not write the copy", written.contains("generated by yt-dlp"))
            assertTrue("dummy cookie lost", written.contains("murem_test"))
            i
        }
        Log.i(TAG, "cookies test: info '${info.videoInfo.title}', copy deleted=${!copy!!.exists()}")
        assertFalse("per-job copy not deleted", copy!!.exists())
        assertArrayEquals("stored cookies.txt changed", CookiesTxt.mergeLines(null, dummy.decodeToString()).toByteArray(), stored.readBytes())
    }

    @Test
    fun copyIsDeletedWhenTheRunFails() {
        val dir = File(work, "cookies")
        var copy: File? = null
        try {
            withJobCookies(store, dir) { cookies ->
                copy = cookies!!.file
                assertTrue(copy!!.exists())
                throw IllegalStateException("boom")
            }
        } catch (_: IllegalStateException) {
        }
        assertFalse(copy!!.exists())
    }

    @Test
    fun noCookiesNoCopy() {
        store.deleteAll()
        val dir = File(work, "cookies")
        withJobCookies(store, dir) { cookies -> assertNull(cookies) }
        assertFalse(File(dir, CookieStore.FILE).exists())
        assertNull(store.summary())
    }
}
